//! Pure model of where an agent's model-view tokens come from, shown by the
//! `/status` popup. Token counts are advisory `cl100k_base` estimates, never
//! billed usage.

/// One origin of model-view tokens.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ContextCategory {
    /// The resolved `SOUL.md` layer (sentinel source, never an absolute path).
    Soul { source: String },
    /// The preamble framing trusted instruction files.
    InstructionSafetyPreamble,
    /// One trusted instruction file, identified by its sentinel source.
    InstructionFile { source: String },
    /// The agent type's persona and the skill advertisement.
    AgentPrompt,
    /// System prompt text whose origin is not known.
    UnattributedSystemPrompt,
    /// Tool schemas plus the tool-protocol instructions.
    ToolSchemas,
    /// The compaction summary or recovery handoff standing in for old messages.
    CompactionSummary,
    /// Content provided by user
    UserMessages,
    /// Content generated by LLM
    AssistantMessages,
    /// Tool calls and their results.
    ToolCalls,
}

/// The coarse grouping the popup's usage table is organised by.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ContextGroup {
    SystemPrompt,
    CompactionSummary,
    UserMessages,
    AssistantMessages,
    ToolCalls,
}

impl ContextGroup {
    pub fn label(self) -> &'static str {
        match self {
            Self::SystemPrompt => "System prompt",
            Self::CompactionSummary => "Compaction summary",
            Self::UserMessages => "User messages",
            Self::AssistantMessages => "Assistant messages",
            Self::ToolCalls => "Tool calls & results",
        }
    }
}

impl ContextCategory {
    pub fn group(&self) -> ContextGroup {
        match self {
            Self::Soul { .. }
            | Self::InstructionSafetyPreamble
            | Self::InstructionFile { .. }
            | Self::AgentPrompt
            | Self::UnattributedSystemPrompt
            | Self::ToolSchemas => ContextGroup::SystemPrompt,
            Self::CompactionSummary => ContextGroup::CompactionSummary,
            Self::UserMessages => ContextGroup::UserMessages,
            Self::AssistantMessages => ContextGroup::AssistantMessages,
            Self::ToolCalls => ContextGroup::ToolCalls,
        }
    }

    pub fn label(&self) -> String {
        match self {
            Self::Soul { source } => format!("Soul ({source})"),
            Self::InstructionSafetyPreamble => "Instruction safety preamble".to_string(),
            Self::InstructionFile { source } => format!("Instructions ({source})"),
            Self::AgentPrompt => "Agent persona & skills".to_string(),
            Self::UnattributedSystemPrompt => "System prompt (origin unknown)".to_string(),
            Self::ToolSchemas => "Tool schemas".to_string(),
            Self::CompactionSummary => ContextGroup::CompactionSummary.label().to_string(),
            Self::UserMessages => ContextGroup::UserMessages.label().to_string(),
            Self::AssistantMessages => ContextGroup::AssistantMessages.label().to_string(),
            Self::ToolCalls => ContextGroup::ToolCalls.label().to_string(),
        }
    }
}

/// Estimated tokens one category contributes to the model view.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ContextSegment {
    pub category: ContextCategory,
    pub tokens: usize,
}

/// Model-view tokens per origin, in display order, measured against the
/// engine's effective context window.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ContextBreakdown {
    segments: Vec<ContextSegment>,
    context_length: usize,
}

impl ContextBreakdown {
    /// `segments` keep the order given; `context_length` is the effective
    /// context window in tokens.
    pub fn new(segments: Vec<ContextSegment>, context_length: usize) -> Self {
        Self {
            segments,
            context_length,
        }
    }

    pub fn segments(&self) -> &[ContextSegment] {
        &self.segments
    }

    pub fn context_length(&self) -> usize {
        self.context_length
    }

    pub fn used_tokens(&self) -> usize {
        self.segments.iter().map(|segment| segment.tokens).sum()
    }

    /// The denominator of every percentage: the context window, or the used
    /// tokens when an estimate overshoots it, so shares never exceed 100%.
    pub fn window_tokens(&self) -> usize {
        self.context_length.max(self.used_tokens())
    }

    pub fn free_tokens(&self) -> usize {
        self.window_tokens() - self.used_tokens()
    }

    pub fn group_tokens(&self, group: ContextGroup) -> usize {
        self.segments
            .iter()
            .filter(|segment| segment.category.group() == group)
            .map(|segment| segment.tokens)
            .sum()
    }

    /// Share of the window `tokens` occupy, in percent (`0.0` for an empty window).
    pub fn percentage(&self, tokens: usize) -> f64 {
        let window = self.window_tokens();
        if window == 0 {
            return 0.0;
        }
        tokens as f64 * 100.0 / window as f64
    }

    /// Share of the used tokens `tokens` make up, in percent (`0.0` when
    /// nothing is used).
    pub fn percentage_of_used(&self, tokens: usize) -> f64 {
        let used = self.used_tokens();
        if used == 0 {
            return 0.0;
        }
        tokens as f64 * 100.0 / used as f64
    }
}

/// Format a percentage with one decimal place, e.g. `12.3%`.
pub fn format_percentage(percentage: f64) -> String {
    format!("{percentage:.1}%")
}

#[cfg(test)]
mod tests {
    use super::*;

    fn segment(category: ContextCategory, tokens: usize) -> ContextSegment {
        ContextSegment { category, tokens }
    }

    #[test]
    fn percentages_are_shares_of_the_window_with_free_space_remaining() {
        let breakdown = ContextBreakdown::new(
            vec![
                segment(ContextCategory::UserMessages, 250),
                segment(ContextCategory::ToolCalls, 125),
            ],
            1000,
        );

        assert_eq!(breakdown.used_tokens(), 375);
        assert_eq!(breakdown.free_tokens(), 625);
        assert_eq!(breakdown.percentage(250), 25.0);
        assert_eq!(format_percentage(breakdown.percentage(125)), "12.5%");
        assert_eq!(format_percentage(breakdown.percentage(1)), "0.1%");
        assert!((breakdown.percentage_of_used(125) - 100.0 / 3.0).abs() < 1e-9);
        assert_eq!(
            ContextBreakdown::new(vec![], 1000).percentage_of_used(5),
            0.0
        );
    }

    #[test]
    fn an_empty_window_yields_zero_percent_instead_of_dividing_by_zero() {
        let breakdown = ContextBreakdown::new(vec![], 0);

        assert_eq!(breakdown.window_tokens(), 0);
        assert_eq!(breakdown.percentage(0), 0.0);
        assert_eq!(breakdown.free_tokens(), 0);
    }

    #[test]
    fn an_overshooting_estimate_is_capped_at_the_whole_window() {
        let breakdown = ContextBreakdown::new(
            vec![
                segment(ContextCategory::UserMessages, 150),
                segment(ContextCategory::AssistantMessages, 50),
            ],
            100,
        );

        assert_eq!(breakdown.window_tokens(), 200);
        assert_eq!(breakdown.free_tokens(), 0);
        assert_eq!(breakdown.percentage(150), 75.0);
    }

    #[test]
    fn segments_keep_their_order_and_group_by_origin() {
        let breakdown = ContextBreakdown::new(
            vec![
                segment(
                    ContextCategory::Soul {
                        source: "built-in".into(),
                    },
                    10,
                ),
                segment(
                    ContextCategory::InstructionFile {
                        source: "sub/AGENTS.md".into(),
                    },
                    20,
                ),
                segment(ContextCategory::ToolSchemas, 30),
                segment(ContextCategory::UserMessages, 5),
            ],
            100,
        );

        let labels: Vec<String> = breakdown
            .segments()
            .iter()
            .map(|segment| segment.category.label())
            .collect();
        assert_eq!(
            labels,
            [
                "Soul (built-in)",
                "Instructions (sub/AGENTS.md)",
                "Tool schemas",
                "User messages"
            ]
        );
        assert_eq!(breakdown.group_tokens(ContextGroup::SystemPrompt), 60);
        assert_eq!(breakdown.group_tokens(ContextGroup::UserMessages), 5);
        assert_eq!(breakdown.group_tokens(ContextGroup::ToolCalls), 0);
    }
}
