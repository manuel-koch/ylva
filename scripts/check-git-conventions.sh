# Single implementation of the Git conventions, used by the lefthook hooks
# and by the CI workflow. See docs/development-workflow.md → "Git hooks".
#
# Usage:
#   check-git-conventions.sh not-main
#   check-git-conventions.sh branch-name [NAME]
#   check-git-conventions.sh commit-message FILE
#   check-git-conventions.sh commit-range REVISION_RANGE

set -euo pipefail

COMMIT_TYPES="feat|fix|docs|style|refactor|perf|test|build|ci|chore|revert"
COMMIT_PATTERN="^(${COMMIT_TYPES})(\\([a-z0-9._/-]+\\))?!?: .+"
BRANCH_PREFIXES="feature|bugfix|hotfix|release|chore|docs|refactor|test"
BRANCH_PATTERN="^(main|(${BRANCH_PREFIXES})/[a-z0-9._-]+)$"
# Branches opened by automation (Dependabot, release-plz); only reachable in CI.
AUTOMATION_BRANCH_PATTERN="^(dependabot/.+|release-plz-.+)$"

fail() {
    echo "error: $*" >&2
    exit 1
}

# True while HEAD is detached or a rebase, merge or cherry-pick is running.
history_operation_in_progress() {
    local git_directory
    git_directory="$(git rev-parse --git-dir)"
    if ! git symbolic-ref --quiet HEAD >/dev/null; then
        return 0
    fi
    [[ -d "${git_directory}/rebase-merge" || -d "${git_directory}/rebase-apply" \
        || -f "${git_directory}/MERGE_HEAD" || -f "${git_directory}/CHERRY_PICK_HEAD" ]]
}

check_not_main() {
    history_operation_in_progress && return 0
    if [[ "$(git symbolic-ref --short HEAD)" == "main" ]]; then
        fail "committing directly on 'main' is not allowed. Create a branch first, e.g. 'git switch -c feature/<name>'."
    fi
}

check_branch_name() {
    local branch_name="${1:-}"
    if [[ -z "${branch_name}" ]]; then
        history_operation_in_progress && return 0
        branch_name="$(git symbolic-ref --short HEAD)"
    fi
    if [[ "${branch_name}" =~ ${AUTOMATION_BRANCH_PATTERN} ]]; then
        return 0
    fi
    if ! [[ "${branch_name}" =~ ${BRANCH_PATTERN} ]]; then
        fail "branch name '${branch_name}' is invalid. Use '<prefix>/<lowercase-kebab-name>' with prefix one of: ${BRANCH_PREFIXES//|/, }."
    fi
}

# Messages generated by Git itself are exempt.
is_generated_subject() {
    [[ "$1" =~ ^(Merge\ |Revert\ \"|fixup!\ |squash!\ |amend!\ ) ]]
}

check_subject() {
    local subject="$1"
    is_generated_subject "${subject}" && return 0
    if ! [[ "${subject}" =~ ${COMMIT_PATTERN} ]]; then
        fail "commit message '${subject}' is not a Conventional Commit. Expected 'type(scope)!: description' with type one of: ${COMMIT_TYPES//|/, }."
    fi
}

check_commit_message() {
    local message_file="${1:-}"
    [[ -f "${message_file}" ]] || fail "commit message file '${message_file}' not found"
    local subject
    subject="$(grep -v '^#' "${message_file}" | sed -n '/./{p;q;}')"
    [[ -n "${subject}" ]] || fail "commit message is empty"
    check_subject "${subject}"
}

check_commit_range() {
    local revision_range="${1:-}"
    [[ -n "${revision_range}" ]] || fail "revision range required"
    local status=0 subject
    while IFS= read -r subject; do
        check_subject "${subject}" || status=1
    done < <(git log --no-merges --format=%s "${revision_range}")
    return "${status}"
}

case "${1:-}" in
    not-main) check_not_main ;;
    branch-name) check_branch_name "${2:-}" ;;
    commit-message) check_commit_message "${2:-}" ;;
    commit-range) check_commit_range "${2:-}" ;;
    *) fail "usage: $0 {not-main|branch-name [NAME]|commit-message FILE|commit-range RANGE}" ;;
esac
